/**
 * Format a number as percentage
 */
function pct(value, decimals = 2) {
  return (value * 100).toFixed(decimals) + '%';
}

/**
 * Format a number as currency
 */
function usd(value, decimals = 2) {
  return '$' + value.toLocaleString('en-US', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  });
}

/**
 * Generate text report
 */
function generateTextReport(results) {
  const { summary, performance, trades } = results;
  const lines = [
    '='.repeat(60),
    '         TradeMind AI - Backtest Report',
    '='.repeat(60),
    '',
    '--- Summary ---',
    `Initial Capital:    ${usd(summary.initialCapital)}`,
    `Final Equity:       ${usd(summary.finalEquity)}`,
    `Total Return:       ${pct(summary.totalReturn)}`,
    `Max Drawdown:       ${pct(summary.maxDrawdown)}`,
    `Trading Days:       ${summary.tradingDays}`,
    `Total Trades:       ${summary.totalTrades}`,
    `Win Rate:           ${pct(summary.winRate)}`,
    '',
    '--- Performance ---',
    `Annualized Return:  ${pct(performance.annualizedReturn)}`,
    `Annualized Vol:     ${pct(performance.annualizedVolatility)}`,
    `Sharpe Ratio:       ${performance.sharpeRatio.toFixed(3)}`,
    `Sortino Ratio:      ${performance.sortinoRatio.toFixed(3)}`,
    `Calmar Ratio:       ${performance.calmarRatio.toFixed(3)}`,
    '',
    '--- Trade Statistics ---',
    `Winners:            ${summary.winningTrades}`,
    `Losers:             ${summary.losingTrades}`,
    `Avg Win:            ${usd(trades.avgWin)}`,
    `Avg Loss:           ${usd(trades.avgLoss)}`,
    `Largest Win:        ${usd(trades.largestWin)}`,
    `Largest Loss:       ${usd(trades.largestLoss)}`,
    `Profit Factor:      ${trades.profitFactor.toFixed(3)}`,
    `Avg Holding Period: ${trades.avgHoldingPeriod.toFixed(1)} bars`,
    `Total Commission:   ${usd(trades.totalCommission)}`,
    `Total Slippage:     ${usd(trades.totalSlippage)}`,
    '',
    '='.repeat(60),
  ];
  return lines.join('\n');
}

/**
 * Generate JSON report
 */
function generateJSONReport(results) {
  return JSON.stringify({
    generatedAt: new Date().toISOString(),
    summary: results.summary,
    performance: results.performance,
    tradeStatistics: results.trades,
    monthlyReturns: calculateMonthlyReturns(results.equity),
    drawdownAnalysis: analyzeDrawdowns(results.equity),
    tradeDistribution: analyzeTradeDistribution(results.tradesList),
  }, null, 2);
}

